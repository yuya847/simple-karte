import { expect, it } from "vitest";
import { SCENARIOS } from "../scenarios";
import { currentEntries, type SessionChanges } from "../record";
import { infusionOrderEntry, infusionRateChangeDraft } from "./infusion-orders";
import { toOrder, type CheckContext } from "../drafts";
import { infusionSnapshot, readInfusionSnapshot, restoreInfusionChanges } from "./use-infusion-persistence";
const blank = (): SessionChanges => ({ added: [], stopped: [] });
it("速度変更・終了と紐付けを同日に復元し、他のオーダ・個人の下書きを保存しない", () => {
 const p = SCENARIOS.patients.find(p => p.id === "99000101")!;
 const inf = SCENARIOS.icu.infusions.find(i => i.patientId === p.id)!;
 const old = infusionOrderEntry(inf, "医師");
 const order = toOrder(infusionRateChangeDraft(old, inf, 2, {day:0,time:"10:00"},"医師","draft"), {drafts:[],activeOrders:[]} as unknown as CheckContext).order!;
 const added = {...old,id:"changed",day:0,time:"10:00",order};
 const other = p.history.find(e=>e.kind==='order'&&e.order.type==='lab')!;
 if(other.kind!=="order") throw new Error("order");
 const charts = {[p.id]:{added:[added,other],stopped:[old.id,other.id],stopTimes:{[old.id]:"10:00"}}, [`${p.id}|医師`]:{added:[added],stopped:[]}};
 const nextInf = {...inf,orderId:added.id,end:{day:0,time:"12:00"}};
 const raw=JSON.stringify(infusionSnapshot("2026-11-07",[nextInf],charts,[p]));
 expect(readInfusionSnapshot(raw,"2026-11-08")).toBeNull();
 const saved=readInfusionSnapshot(raw,"2026-11-07")!;
 expect(Object.keys(saved.charts)).toEqual([p.id]);
 expect(saved.infusions[0]).toMatchObject({orderId:"changed",end:{day:0,time:"12:00"}});
 const restored=restoreInfusionChanges({},saved,blank);
 expect(restored[p.id].added).toHaveLength(1);
 expect(restored[p.id].stopped).toEqual([old.id]);
 expect(currentEntries(p,restored[p.id]).find(e=>e.id===old.id)).toMatchObject({status:"中止"});
 expect(restoreInfusionChanges(restored,saved,blank)[p.id].added).toHaveLength(1);
 expect(readInfusionSnapshot("bad json","2026-11-07")).toBeNull();
});
