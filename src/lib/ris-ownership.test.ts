import { expect, it } from "vitest";
import { SCENARIOS } from "./scenarios";
import { visitPerson } from "./lab-visits";
import { EMPTY_DESK } from "./lab-desk";
import { putWork, risRows } from "./ris";
import { migrateRisOwners } from "./ris-ownership";
import { risTakeFields } from "./ris-take";
it("同一患者の病棟・救急検査は一覧・受付・撮影・予約・照射録を共有しない", () => {
 const p = SCENARIOS.patients.find(p => p.id === "99000002")!;
 const visit = visitPerson("er", SCENARIOS.er.find(v => v.id === p.id)!, SCENARIOS.visitOrders[`er:${p.id}`] ?? [], EMPTY_DESK, p);
 const ward = {patient:p, room:p.room, entries:p.history.filter(e => e.kind === "order")};
 const people = [ward, {...visit, entries: visit.patient.history.filter(e => e.kind === "order")}];
 const rows = risRows(people, SCENARIOS.ris);
 expect(new Set(rows.map(r => r.orderId)).size).toBe(rows.length);
 expect(rows.some(r => r.patientId === visit.patient.id)).toBe(true);
 expect(risRows([...people, ward], SCENARIOS.ris)).toHaveLength(rows.length);
 const r = rows.find(r => r.patientId === p.id)!;
 const changed = putWork(SCENARIOS.ris, r, w => ({...w, arrived:{day:0,time:"09:00",by:"試験"}, started:{day:0,time:"09:10",by:"試験",via:"手入力"}, room:"PORT", slot:{day:0,time:"19:00"}, record:{day:0,time:"09:20",by:"試験"}}));
 for (const er of rows.filter(r => r.patientId === visit.patient.id)) expect(changed[er.orderId]).toEqual(SCENARIOS.ris[er.orderId]);
 const emergency = rows.find(x => x.patientId === visit.patient.id)!;
 const erChanged = putWork(changed, emergency, w => ({...w, arrived:{day:0,time:"10:00",by:"救急試験"}, slot:{day:0,time:"20:00"}}));
 expect(erChanged[r.orderId]).toEqual(changed[r.orderId]);
 const updated = risRows(people, changed).find(x => x.orderId === r.orderId)!;
 expect(risTakeFields(updated, {y:2026,m:11,d:7}).find(f => f.label === "予定")?.value).toContain("19:00");
 const legacy = {...changed, [r.orderId]: {...changed[r.orderId], patientId:visit.patient.id}};
 const migrated = migrateRisOwners(legacy, people);
 expect(migrated[r.orderId]).toEqual(changed[r.orderId]);
 expect(migrateRisOwners(migrated, people)).toBe(migrated);
});
