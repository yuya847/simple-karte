/** [official code (e.g. "J0453ｲ", "K783-2"; a 4-digit number is a ダミーコード for a drug), name, 対応コード]. */
export type DpcItem = readonly [code: string, name: string, branch: string];

export interface DpcRow {
  /** 番号 in the 電子点数表 (sheet 11). */
  no: number;
  code: string;
  /** The words of the 点数表 columns (手術名・手術・処置等１・２・定義副傷病・重症度等). */
  label: { surgery?: string; shochi1?: string; shochi2?: string; fukushobyo?: string; severity?: string };
  /** 入院日Ⅰ・Ⅱ・Ⅲ（日）; null = no points: 包括の対象外 (医科点数表で算定). */
  days: readonly [number, number, number] | null;
  /** 点数（点）for 入院期間Ⅰ・Ⅱ・Ⅲ（1日につき）. */
  points: readonly [number, number, number] | null;
}

export interface DpcClass {
  /** 上6桁 (MDC 2桁 + 分類 4桁). */
  code: string;
  name: string;
  mdcName: string;
  /** ICD-10 of 医療資源を最も投入した傷病名 that fall in this class ("$" = the code and every subcode). */
  icd: readonly (readonly [pattern: string, name: string])[];
  /** 年齢 split (sheet ５): age below `below` → `under`, else `over`. */
  age?: { below: number; under: string; over: string; label: string };
  /** 重症度等 that is the admission route (sheet 10－2, 条件区分 13). */
  transfer?: { no: string; yes: string };
  /** 手術 branches as they stand in the tree, top to bottom (99 なし first). */
  surgeryTree: readonly string[];
  /** 手術 with their own branch (対応コード other than 97). Any other operation is 97. */
  surgery: readonly DpcItem[];
  shochi1: readonly DpcItem[];
  shochi2: readonly DpcItem[];
  /** [ICD-10, name, 対応コード, フラグ（1 共通 / 2 手術なし / 3 手術あり）]. */
  fukushobyo: readonly (readonly [string, string, string, string])[];
  /**
   * 変換テーブル (sheet 12): [DPC code, 包括フラグ, 年齢, 手術, 手術・処置等１, 手術・処置等２, 定義副傷病, 転院].
   * "" or "a" = any value.
   */
  conv: readonly (readonly [string, string, string, string, string, string, string, string])[];
  rows: readonly DpcRow[];
}

