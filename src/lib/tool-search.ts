/** Whether a tool's name matches what was typed (an empty box matches every tool). */
export function toolMatches(label: string, typed: string): boolean {
  if (!searchKey(typed)) return true;
  return kanaMatch(label, typed) || (TOOL_READINGS[label] ?? []).some((r) => kanaMatch(r, typed));
}
